// One LSP connection per (scopeRoot, language): handshake, document sync, diagnostics, crash recovery.
import { createMessageConnection, CancellationTokenSource, type CancellationToken, type MessageConnection } from "vscode-jsonrpc/browser";
import type * as lsp from "vscode-languageserver-protocol";
import type * as M from "monaco-editor";
import { bus, type BusChannel } from "../bus";
import { ensureMonaco } from "../monaco-setup";
import { BusMessageReader, BusMessageWriter } from "./transport";
import { fromRange, lspLanguageId, toMarker } from "./convert";

export interface BridgeHost {
  /** One-time user-facing notice (e.g. server not installed). */
  notify(message: string): void;
  /** Ensure a model exists for a uri so Monaco can show peeks / apply edits to it. */
  ensureModel(uri: M.Uri): Promise<void>;
}

type LSPServiceModule = { Acquire(scopeRoot: string, languageId: string): Promise<string> };
// LSPService bindings are generated by Go; guard so the bridge no-ops until they exist.
const lspMods = import.meta.glob<LSPServiceModule>("../bindings/github.com/sid/harness/internal/app/lspservice.ts");
async function acquire(root: string, lang: string): Promise<string | undefined> {
  const load = Object.values(lspMods)[0];
  if (!load) return undefined;
  return (await load()).Acquire(root, lang);
}

function errCode(e: unknown): { code: string; message: string } {
  const x = e as { cause?: unknown; message?: string };
  let c: unknown = x?.cause ?? x;
  if (typeof c === "string") {
    try { c = JSON.parse(c); } catch { /* plain */ }
  }
  const o = c as { code?: string; message?: string };
  if (o && typeof o.code === "string") return { code: o.code, message: o.message ?? "" };
  return { code: "internal", message: x?.message ?? String(e) };
}

type Doc = { model: M.editor.ITextModel; refs: number; timer?: ReturnType<typeof setTimeout>; dirty: boolean; off: M.IDisposable; path: string };

const warned = new Set<string>();
const MAX_ATTEMPTS = 6;

export class LspClient {
  conn: MessageConnection | null = null;
  caps: lsp.ServerCapabilities | null = null;
  readonly docs = new Map<string, Doc>();
  readonly diag = new Map<string, lsp.Diagnostic[]>();
  state: "idle" | "starting" | "ready" | "failed" = "idle";
  private ch: BusChannel | null = null;
  private attempts = 0;
  private retryTimer?: ReturnType<typeof setTimeout>;
  private disposed = false;
  private epoch = 0;
  constructor(
    readonly root: string,
    readonly lang: string,
    private host: BridgeHost,
    private onReady: (c: LspClient) => void,
  ) {}

  get id() { return this.root + "\n" + this.lang; }

  async start(): Promise<void> {
    if (this.disposed || this.state === "starting" || this.state === "ready") return;
    this.state = "starting";
    const epoch = ++this.epoch;
    try {
      const key = await acquire(this.root, this.lang);
      if (key === undefined) { this.state = "failed"; return; } // no LSPService binding yet
      if (this.disposed || epoch !== this.epoch) return;
      const ch = bus.open("lsp/" + key);
      this.ch = ch;
      const crash = () => { if (epoch === this.epoch) this.crashed(); };
      const reader = new BusMessageReader(ch, (s) => { if (s.state === "crashed") crash(); });
      const conn = createMessageConnection(reader, new BusMessageWriter(ch));
      this.conn = conn;
      this.wire(conn);
      conn.onClose(crash);
      conn.onError(() => {});
      conn.listen();
      const res = await conn.sendRequest<lsp.InitializeResult>("initialize", this.initParams());
      if (this.disposed || epoch !== this.epoch) return;
      void conn.sendNotification("initialized", {});
      this.caps = res.capabilities;
      this.state = "ready";
      this.attempts = 0;
      this.onReady(this);
      for (const d of this.docs.values()) this.sendOpen(d);
      for (const [uri, ds] of this.diag) this.applyDiag(uri, ds);
    } catch (e) {
      const { code, message } = errCode(e);
      this.teardown();
      this.state = "failed";
      if (code === "not_found") {
        const k = "nf:" + this.lang;
        if (!warned.has(k)) { warned.add(k); this.host.notify(message || `Language server for ${this.lang} not found`); }
        return;
      }
      console.warn("[lsp] start failed", this.lang, message);
      this.scheduleRestart();
    }
  }

  private initParams(): lsp.InitializeParams {
    const rootUri = ensureMonaco().Uri.file(this.root).toString();
    const dyn = { dynamicRegistration: false };
    return {
      processId: null,
      clientInfo: { name: "harness" },
      rootUri,
      workspaceFolders: [{ uri: rootUri, name: this.root.split("/").pop() || "root" }],
      capabilities: {
        workspace: { applyEdit: true, workspaceEdit: { documentChanges: true }, configuration: true, workspaceFolders: true },
        textDocument: {
          synchronization: { didSave: true, dynamicRegistration: false },
          completion: {
            completionItem: { snippetSupport: true, documentationFormat: ["markdown", "plaintext"], deprecatedSupport: true, tagSupport: { valueSet: [1] }, labelDetailsSupport: true, resolveSupport: { properties: ["documentation", "detail", "additionalTextEdits"] } },
            contextSupport: true,
          },
          hover: { contentFormat: ["markdown", "plaintext"] },
          signatureHelp: { signatureInformation: { documentationFormat: ["markdown", "plaintext"], parameterInformation: { labelOffsetSupport: true }, activeParameterSupport: true }, contextSupport: true },
          definition: { linkSupport: true },
          references: dyn,
          documentSymbol: { hierarchicalDocumentSymbolSupport: true },
          rename: { prepareSupport: true },
          formatting: dyn,
          rangeFormatting: dyn,
          codeAction: { codeActionLiteralSupport: { codeActionKind: { valueSet: ["", "quickfix", "refactor", "source"] } }, isPreferredSupport: true, resolveSupport: { properties: ["edit"] } },
          publishDiagnostics: { relatedInformation: false, tagSupport: { valueSet: [1, 2] } },
        },
        window: { workDoneProgress: false },
      },
    };
  }

  private wire(conn: MessageConnection) {
    conn.onNotification("textDocument/publishDiagnostics", (p: lsp.PublishDiagnosticsParams) => {
      const key = ensureMonaco().Uri.parse(p.uri).toString();
      this.diag.set(key, p.diagnostics);
      this.applyDiag(key, p.diagnostics);
    });
    conn.onRequest("workspace/configuration", (p: lsp.ConfigurationParams) => p.items.map(() => null));
    conn.onRequest("client/registerCapability", () => null);
    conn.onRequest("client/unregisterCapability", () => null);
    conn.onRequest("window/workDoneProgress/create", () => null);
    conn.onRequest("workspace/workspaceFolders", () => [{ uri: ensureMonaco().Uri.file(this.root).toString(), name: "root" }]);
    conn.onRequest("workspace/applyEdit", (p: lsp.ApplyWorkspaceEditParams): lsp.ApplyWorkspaceEditResult => ({ applied: this.applyEdit(p.edit) }));
    conn.onNotification("window/logMessage", () => {});
    conn.onNotification("window/showMessage", () => {});
    conn.onNotification("$/progress", () => {});
  }

  private applyEdit(we: lsp.WorkspaceEdit): boolean {
    const m = ensureMonaco();
    const per = new Map<string, lsp.TextEdit[]>();
    if (we.documentChanges) for (const dc of we.documentChanges) if ("edits" in dc) per.set(dc.textDocument.uri, dc.edits.filter((e): e is lsp.TextEdit => "newText" in e));
    if (we.changes) for (const [u, es] of Object.entries(we.changes)) per.set(u, es);
    let ok = true;
    for (const [uri, es] of per) {
      const model = m.editor.getModel(m.Uri.parse(uri));
      if (!model) { ok = false; continue; }
      model.pushEditOperations([], es.map((e) => ({ range: fromRange(e.range), text: e.newText })), () => null);
    }
    return ok;
  }

  private applyDiag(uri: string, ds: lsp.Diagnostic[]) {
    const m = ensureMonaco();
    const model = this.docs.get(uri)?.model;
    if (model) m.editor.setModelMarkers(model, "lsp:" + this.lang, ds.map(toMarker));
  }

  // ---- document sync ----

  attach(model: M.editor.ITextModel, path: string): void {
    const uri = model.uri.toString();
    const ex = this.docs.get(uri);
    if (ex) { ex.refs++; return; }
    const doc: Doc = { model, refs: 1, dirty: false, path, off: model.onDidChangeContent(() => this.changed(uri)) };
    this.docs.set(uri, doc);
    if (this.state === "ready") {
      this.sendOpen(doc);
      const ds = this.diag.get(uri);
      if (ds) this.applyDiag(uri, ds);
    } else void this.start();
  }

  detach(model: M.editor.ITextModel): void {
    const uri = model.uri.toString();
    const d = this.docs.get(uri);
    if (!d || --d.refs > 0) return;
    this.closeDoc(uri, d);
  }

  private closeDoc(uri: string, d: Doc) {
    d.off.dispose();
    if (d.timer) clearTimeout(d.timer);
    this.docs.delete(uri);
    if (!d.model.isDisposed()) ensureMonaco().editor.setModelMarkers(d.model, "lsp:" + this.lang, []);
    if (this.state === "ready") void this.conn?.sendNotification("textDocument/didClose", { textDocument: { uri } });
  }

  private sendOpen(d: Doc) {
    void this.conn?.sendNotification("textDocument/didOpen", {
      textDocument: { uri: d.model.uri.toString(), languageId: lspLanguageId(this.lang, d.path), version: d.model.getVersionId(), text: d.model.getValue() },
    });
    d.dirty = false;
  }

  private changed(uri: string) {
    const d = this.docs.get(uri);
    if (!d || this.state !== "ready") return;
    d.dirty = true;
    if (!d.timer) d.timer = setTimeout(() => this.flushDoc(uri), 40);
  }

  /** Send pending full-sync changes now (before requests that depend on the latest text). */
  flushDoc(uri: string): void {
    const d = this.docs.get(uri);
    if (!d) return;
    if (d.timer) clearTimeout(d.timer);
    d.timer = undefined;
    if (!d.dirty || this.state !== "ready") return;
    d.dirty = false;
    void this.conn?.sendNotification("textDocument/didChange", {
      textDocument: { uri, version: d.model.getVersionId() },
      contentChanges: [{ text: d.model.getValue() }],
    });
  }

  didSave(model: M.editor.ITextModel): void {
    const uri = model.uri.toString();
    if (!this.docs.has(uri) || this.state !== "ready") return;
    this.flushDoc(uri);
    void this.conn?.sendNotification("textDocument/didSave", { textDocument: { uri }, text: model.getValue() });
  }

  // ---- requests ----

  async request<R>(method: string, params: unknown, token?: M.CancellationToken, uri?: string): Promise<R | null> {
    if (this.state !== "ready" || !this.conn) return null;
    if (uri) this.flushDoc(uri);
    let ct: CancellationToken | undefined;
    if (token) {
      const src = new CancellationTokenSource();
      token.onCancellationRequested(() => src.cancel());
      ct = src.token;
    }
    try {
      return await this.conn.sendRequest<R>(method, params, ct);
    } catch {
      return null;
    }
  }

  // ---- lifecycle ----

  private teardown() {
    this.epoch++;
    const ch = this.ch;
    this.ch = null;
    const c = this.conn;
    this.conn = null;
    try { c?.dispose(); } catch { /* ignore */ }
    ch?.close();
    this.caps = null;
  }

  private crashed() {
    if (this.disposed || this.state === "idle") return;
    this.teardown();
    this.state = "idle";
    for (const d of this.docs.values()) { d.dirty = false; if (d.timer) clearTimeout(d.timer); d.timer = undefined; }
    this.scheduleRestart();
  }

  private scheduleRestart() {
    if (this.disposed || this.retryTimer || this.attempts >= MAX_ATTEMPTS) return;
    const delay = Math.min(30_000, 1000 * 2 ** this.attempts++);
    this.retryTimer = setTimeout(() => { this.retryTimer = undefined; this.state = "idle"; void this.start(); }, delay);
  }

  dispose(): void {
    this.disposed = true;
    if (this.retryTimer) clearTimeout(this.retryTimer);
    for (const [u, d] of [...this.docs]) this.closeDoc(u, d);
    this.teardown();
  }
}
